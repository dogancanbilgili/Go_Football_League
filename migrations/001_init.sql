-- =============================================================
-- TABLE: teams
-- EA FC 26 ratings (sofifa.com): Attack, Midfield, Defence.
-- Attack and Defence drive match simulation; Midfield drives predictions.
-- =============================================================
CREATE TABLE IF NOT EXISTS teams (
    id       SERIAL       PRIMARY KEY,
    name     VARCHAR(100) NOT NULL UNIQUE,
    attack   INT          NOT NULL CHECK (attack   BETWEEN 1 AND 99),
    midfield INT          NOT NULL CHECK (midfield BETWEEN 1 AND 99),
    defence  INT          NOT NULL CHECK (defence  BETWEEN 1 AND 99)
);

-- =============================================================
-- TABLE: matches
-- Fixtures are generated by the Go seeder (pkg/database/seed.go)
-- using the circle-method round-robin algorithm — not hardcoded here.
-- Week range covers a full 20-team season: 2*(20-1) = 38 weeks.
-- =============================================================
CREATE TABLE IF NOT EXISTS matches (
    id           SERIAL  PRIMARY KEY,
    week         INT     NOT NULL CHECK (week BETWEEN 1 AND 38),
    home_team_id INT     NOT NULL REFERENCES teams(id),
    away_team_id INT     NOT NULL REFERENCES teams(id),
    home_goals   INT     DEFAULT NULL CHECK (home_goals >= 0),
    away_goals   INT     DEFAULT NULL CHECK (away_goals >= 0),
    played       BOOLEAN NOT NULL DEFAULT false,

    CONSTRAINT different_teams CHECK (home_team_id <> away_team_id)
);

